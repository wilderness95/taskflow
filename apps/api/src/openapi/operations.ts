export type Operation = {
  method: 'get' | 'post' | 'put' | 'patch' | 'delete'
  /** OpenAPI-formátumú útvonal (`/boards/{id}`), a `/api/v1` előtag nélkül. */
  path: string
  tag: string
  summary: string
  query?: z.ZodObject
  body?: z.ZodType
  /** Sikeres státusz és válasz; séma nélkül nincs törzs (204). */
  success: { status: 101 | 200 | 201 | 202 | 204; schema?: z.ZodType }
  /** Nyilvános végpont: nem kell hozzá bejelentkezés. */
  public?: boolean
  /** A műveletre jellemző hibakódok a 400/404 mellett. */
  errors?: number[]
  /** A sikeres válasz nem JSON, hanem esemény-folyam (`text/event-stream`). */
  stream?: boolean | 'list'
  /** A kérés törzse a fájl nyers tartalma (`application/octet-stream`). */
  upload?: boolean
  /** A sikeres válasz a fájl nyers tartalma. */
  download?: boolean
  /** Hosszabb leírás (pl. a WebSocket protokoll; ilyenkor a sikeres válasz a 101). */
  description?: string
}

